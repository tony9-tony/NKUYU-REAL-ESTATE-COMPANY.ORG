  const SKIP = "script, style, textarea, code:not(.i18n-ok), pre, .mono, .docx-page, .docx-preview, .contract-preview, [contenteditable], [data-no-i18n]";
  const ATTRS = ["placeholder", "title", "aria-label"];

  function translateText(node) {
    const raw = node.nodeValue;
    if (!raw || !/[A-Za-z]/.test(raw)) return;
    const trimmed = raw.trim();
    if (!trimmed) return;
    const parent = node.parentElement;
    if (!parent || parent.closest(SKIP)) return;
    const out = translate(trimmed);
    if (out !== null && out !== trimmed) node.nodeValue = raw.replace(trimmed, out);
  }
  function translateAttributes(element) {
    if (element.closest(SKIP)) return;
    for (const name of ATTRS) {
      const value = element.getAttribute(name);
      if (!value) continue;
      const out = translate(value.trim());
      if (out !== null && out !== value) element.setAttribute(name, out);
    }
  }
  function translateTree(root) {
    if (lang !== "sw" || !root) return;
    if (root.nodeType === Node.TEXT_NODE) { translateText(root); return; }
    if (root.nodeType !== Node.ELEMENT_NODE) return;
    if (root.closest && root.closest(SKIP)) return;
    translateAttributes(root);
    // Elements in SKIP are rejected with their whole subtree.
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
      acceptNode: (node) => (node.nodeType === Node.ELEMENT_NODE && node.matches(SKIP) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
    });
    let node = walker.nextNode();
    while (node) {
      if (node.nodeType === Node.TEXT_NODE) translateText(node); else translateAttributes(node);
      node = walker.nextNode();
    }
  }

