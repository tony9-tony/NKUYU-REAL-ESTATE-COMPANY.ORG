/**
 * Repair leftover display names from retired roles.
 *
 * A demo user was once created with the display name "Sales and Marketing
 * Officer", which is the name of a role that no longer exists. Only the display
 * name is rewritten: the user row, its id, and every record it owns are left
 * untouched, so no membership or business data is lost. A person is never
 * renamed to a role they do not hold.
 */
async function repairRetiredRoleDisplayNames() {
  const retired = Object.keys(ROLE_REPLACEMENTS);
  if (!retired.length) return;
  const org = await organizationId();
  const users = await query(
    `SELECT u.id,u.display_name,u.email,
            COALESCE((SELECT r.name FROM user_roles ur JOIN roles r ON r.id=ur.role_id
                       WHERE ur.user_id=u.id ORDER BY r.rank DESC LIMIT 1),'') AS current_role
       FROM users u WHERE u.organization_id=$1 AND u.display_name=ANY($2::text[])`,
    [org, retired],
  );
  for (const user of users.rows) {
    if (user.current_role === user.display_name) {
      // The name was still accurate: keep it, the role exists under it.
      continue;
    }
    const replacement = user.current_role || "MKUYU Staff";
    // `<role> · <email local part>` stays unique and traceable to the original.
    const newName = `${replacement} (${String(user.email).split("@")[0]})`.slice(0, 80);
    await query("UPDATE users SET display_name=$1 WHERE id=$2", [newName, user.id]);
    console.log(`renamed stale display name "${user.display_name}" -> "${newName}" (user ${user.id}, role "${user.current_role}")`);
  }
}

/**
 * Rotate the passwords of the legacy accounts that predate the demo set.
 *
 * Deliberately narrow: this touches `password_hash` and nothing else. The user
 * id, email, display name, `role` column, user_roles, user_departments and every
 * owned record stay exactly as they were. Sessions are dropped so a token issued
 * against the old credential cannot outlive the rotation.
 *
 * Records an audit event per rotation so the change is traceable.
 */
async function rotateLegacyPasswords() {
  const org = await organizationId();
  for (const account of LEGACY_ACCOUNTS) {
    const user = await queryOne("SELECT id,email,password_hash FROM users WHERE email=$1 AND organization_id=$2", [account.email, org]);
    if (!user) continue;
    const target = legacyPasswordFor(account.email);
    // Idempotent in two independent parts, so a server restart never churns
    // hashes or drops live sessions, and a rotation that happened before its
    // audit event was recorded still gets the event.
    if (!verifyPassword(target, user.password_hash)) {
      await query("UPDATE users SET password_hash=$1 WHERE id=$2", [hashPassword(target), user.id]);
      await query("DELETE FROM sessions WHERE user_id=$1", [user.id]);
      console.log(`rotated the password for ${account.email} (user ${user.id}); preserved id, role, department and history`);
    }
    const audited = await queryOne(
      "SELECT 1 FROM audit_logs WHERE user_id=$1 AND action='password_rotated' LIMIT 1", [user.id],
    );
    if (!audited) {
      await query(
        `INSERT INTO audit_logs (organization_id,user_id,action,module,record_id,details_json)
         VALUES ($1,$2,'password_rotated','user',$3,$4::jsonb)`,
        [org, user.id, String(user.id), JSON.stringify({ email: account.email, reason: "legacy demo credential rotation", sessions_invalidated: true })],
      );
    }
  }
}

async function seedDemoAccounts() {
  const org = await organizationId();
  for (const account of demoAccounts) {
    const role = await queryOne("SELECT id FROM roles WHERE organization_id=$1 AND name=$2", [org, account.role]);
    const department = await queryOne("SELECT id FROM departments WHERE organization_id=$1 AND name=$2", [org, account.department]);
    if (!role || !department) {
      console.warn(`demo seed skipped ${account.email}: role or department missing`);
      continue;
    }
    const password = demoPasswordFor(account.email);
    const existing = await queryOne("SELECT id FROM users WHERE email=$1", [account.email]);
    let userId;
    if (existing) {
      // Reset the demo password and repair the display name from a retired role.
      await query("UPDATE users SET display_name=$1, password_hash=$2, active=TRUE WHERE id=$3", [account.display_name, hashPassword(password), existing.id]);
      userId = existing.id;
    } else {
      const created = await queryOne(
        "INSERT INTO users (organization_id, email, password_hash, display_name, role) VALUES ($1,$2,$3,$4,'staff') RETURNING id",
        [org, account.email, hashPassword(password), account.display_name],
      );
      userId = created.id;
    }
    // Exactly one role and one department, so a demo account can never drift
    // outside the permissions its role defines.
    await withTransaction(async (client) => {
      await client.query("DELETE FROM user_roles WHERE user_id=$1", [userId]);
      await client.query("INSERT INTO user_roles (user_id, role_id) VALUES ($1,$2)", [userId, role.id]);
      await client.query("DELETE FROM user_departments WHERE user_id=$1", [userId]);
      await client.query("INSERT INTO user_departments (user_id, department_id) VALUES ($1,$2)", [userId, department.id]);
    });
  }
}

