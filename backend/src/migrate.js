/**
 * Widens the `debts.status` CHECK to include `partial`.
 *
 * An installment that has received some but not all of its money is a real state
 * that Finance needs to see, so the column's vocabulary has to admit it. This is
 * the only structural change the partial-status work requires: no column is
 * added, dropped or retyped, and no existing row is rewritten.
 *
 * Idempotent, and safe on a fresh database (the drop is IF EXISTS). The
 * constraint is dropped before being re-added because Postgres has no
 * "replace constraint" and the original is auto-named.
 *
 * The advisory lock serialises the drop-then-add pair across processes: two
 * servers booting at the same time would otherwise both drop, and the second
 * would fail with "constraint already exists".
 */
async function migrateInstallmentStatus() {
  await withTransaction(async (client) => {
    await client.query("SELECT pg_advisory_xact_lock(88102)");
    await client.query("ALTER TABLE debts DROP CONSTRAINT IF EXISTS debts_status_check");
    await client.query(`ALTER TABLE debts ADD CONSTRAINT debts_status_check CHECK (status IN (${DEBT_STATUSES.map((status) => `'${status}'`).join(",")}))`);
  });
}


