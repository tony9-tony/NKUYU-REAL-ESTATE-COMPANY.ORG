async function migratePaymentApproval() {
  const had = await queryOne("SELECT 1 AS ok FROM information_schema.columns WHERE table_name='payments' AND column_name='status'");
  await query("ALTER TABLE payments ADD COLUMN IF NOT EXISTS status TEXT");
  await query("ALTER TABLE payments ADD COLUMN IF NOT EXISTS approved_by INTEGER REFERENCES users(id) ON DELETE SET NULL");
  await query("ALTER TABLE payments ADD COLUMN IF NOT EXISTS approved_at TIMESTAMPTZ");
  if (!had) await query("UPDATE payments SET status='approved' WHERE status IS NULL");
  await query("UPDATE payments SET status='pending' WHERE status IS NULL");
  await query("ALTER TABLE payments ALTER COLUMN status SET DEFAULT 'pending'");
  await query("ALTER TABLE payments ALTER COLUMN status SET NOT NULL");
  await query("ALTER TABLE payments DROP CONSTRAINT IF EXISTS payments_status_check");
  await query("ALTER TABLE payments ADD CONSTRAINT payments_status_check CHECK (status IN ('pending','approved','reversed'))");
  // Payment safety (phase 1): the evidence behind a payment, and a reversal that
  // keeps the record instead of deleting it.
  await query("ALTER TABLE payments ADD COLUMN IF NOT EXISTS evidence_text TEXT");
  await query("ALTER TABLE payments ADD COLUMN IF NOT EXISTS reversed_by INTEGER REFERENCES users(id) ON DELETE SET NULL");
  await query("ALTER TABLE payments ADD COLUMN IF NOT EXISTS reversed_at TIMESTAMPTZ");
  await query("ALTER TABLE payments ADD COLUMN IF NOT EXISTS reversal_reason TEXT");
  // Set when the only Finance person approved a payment they recorded themselves
  // (single-Finance mode); kept on the record so the MD can review those.
  await query("ALTER TABLE payments ADD COLUMN IF NOT EXISTS self_approved BOOLEAN NOT NULL DEFAULT FALSE");
  // How an approved payment is spread over a contract's installments: oldest
  // unpaid first, any surplus onto the next. One payment may settle several
  // installments; an installment's paid amount is the sum of its allocations.
  await query(`CREATE TABLE IF NOT EXISTS payment_allocations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id INTEGER REFERENCES organizations(id) ON DELETE CASCADE,
    payment_id INTEGER NOT NULL REFERENCES payments(id) ON DELETE CASCADE,
    debt_id INTEGER NOT NULL REFERENCES debts(id) ON DELETE CASCADE,
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())`);
  await query("CREATE INDEX IF NOT EXISTS idx_payment_allocations_debt ON payment_allocations(debt_id)");
  await query("CREATE INDEX IF NOT EXISTS idx_payment_allocations_payment ON payment_allocations(payment_id)");
  // MKUYU's own receipt number, issued when a payment is approved.
  await query("CREATE SEQUENCE IF NOT EXISTS payment_receipt_seq");
  await query("ALTER TABLE payments ADD COLUMN IF NOT EXISTS receipt_number TEXT");
  await query("CREATE UNIQUE INDEX IF NOT EXISTS idx_payments_receipt_number ON payments(receipt_number) WHERE receipt_number IS NOT NULL");
  await query(`UPDATE payments SET receipt_number = 'RCT-' || to_char(COALESCE(approved_at, created_at), 'YYYY') || '-' || lpad(nextval('payment_receipt_seq')::text, 6, '0')
     WHERE status IN ('approved','reversed') AND receipt_number IS NULL`);
  // Money paid back to a customer (a lease's security deposit, a cancelled deal).
  // Recorded with its reference and proof, confirmed like a payment.
  await query(`CREATE TABLE IF NOT EXISTS refunds (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id INTEGER REFERENCES organizations(id) ON DELETE CASCADE,
    contract_id INTEGER NOT NULL REFERENCES contracts(id) ON DELETE RESTRICT,
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    paid_at DATE NOT NULL,
    method TEXT NOT NULL DEFAULT 'bank',
    reference TEXT NOT NULL,
    reason TEXT NOT NULL,
    evidence_text TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved')),
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    approved_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    approved_at TIMESTAMPTZ,
    self_approved BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())`);
  await query("CREATE INDEX IF NOT EXISTS idx_refunds_contract ON refunds(contract_id)");
  // Payments approved before allocations existed keep exactly what they paid:
  // their whole amount on the installment they were recorded against.
  await query(`INSERT INTO payment_allocations (organization_id, payment_id, debt_id, amount)
    SELECT p.organization_id, p.id, p.debt_id, p.amount FROM payments p
     WHERE p.status = 'approved' AND p.debt_id IS NOT NULL AND p.amount > 0
       AND NOT EXISTS (SELECT 1 FROM payment_allocations pa WHERE pa.payment_id = p.id)`);
  // One transaction reference may back only one live payment. The index is the
  // database's own guarantee; the API checks first so it can explain the clash.
  // Older data may already hold duplicates: then the index is left out (and the
  // API check still protects every new payment) rather than failing startup.
  const duplicates = await queryOne(`SELECT COUNT(*)::int AS n FROM (
      SELECT 1 FROM payments WHERE reference IS NOT NULL AND btrim(reference) <> '' AND status <> 'reversed'
      GROUP BY organization_id, upper(regexp_replace(reference, '\\s', '', 'g')) HAVING COUNT(*) > 1) d`);
  if (!duplicates?.n) {
    await query(`CREATE UNIQUE INDEX IF NOT EXISTS idx_payments_reference_unique
      ON payments (organization_id, upper(regexp_replace(reference, '\\s', '', 'g')))
      WHERE reference IS NOT NULL AND btrim(reference) <> '' AND status <> 'reversed'`);
  } else {
    console.warn(`payments: ${duplicates.n} transaction reference(s) are used more than once; the unique index was not created. Review them in Payments.`);
  }
}

