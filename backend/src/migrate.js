/**
 * Widens the `debts.status` CHECK to include `partial`.
 *
 * An installment that has received some but not all of its money is a real state
 * that Finance needs to see, so the column's vocabulary has to admit it. This is
 * the only structural change the partial-status work requires: no column is
 * added, dropped or retyped, and no existing row is rewritten.
 *
 * Idempotent, and safe on a fresh database (the drop is IF EXISTS). The
 * constraint is dropped before being re-added because Postgres has no
 * "replace constraint" and the original is auto-named.
 *
 * The advisory lock serialises the drop-then-add pair across processes: two
 * servers booting at the same time would otherwise both drop, and the second
 * would fail with "constraint already exists".
 */
async function migrateInstallmentStatus() {
  await withTransaction(async (client) => {
    await client.query("SELECT pg_advisory_xact_lock(88102)");
    await client.query("ALTER TABLE debts DROP CONSTRAINT IF EXISTS debts_status_check");
    await client.query(`ALTER TABLE debts ADD CONSTRAINT debts_status_check CHECK (status IN (${DEBT_STATUSES.map((status) => `'${status}'`).join(",")}))`);
  });
}


/**
 * Phase 2.1: contract pricing columns.
 *
 * `contracts.value` stays the single authoritative contract amount and is
 * redefined as the FINAL PRICE, so every existing consumer (payment schedule,
 * reports, exports, dashboards) keeps reading one number and there is no second
 * definition of "what this contract is worth" that could drift.
 *
 * Only the two inputs and the calculated discount are stored alongside it. A
 * separate `final_price` column is deliberately NOT added: it would duplicate
 * `value` and the two could disagree. The API exposes `final_price` as an alias
 * of `value` so callers see the pricing breakdown without a redundant column.
 *
 * Backfill is safe and conservative: a contract that predates this feature has no
 * historical discount record, so it is treated as list price with no discount and
 * its existing financial value is preserved exactly. No historical discount is
 * ever invented.
 */
async function migrateContractPricing() {
  await query("ALTER TABLE contracts ADD COLUMN IF NOT EXISTS original_price NUMERIC(14,2)");
  await query("ALTER TABLE contracts ADD COLUMN IF NOT EXISTS discount_pct NUMERIC(5,2) NOT NULL DEFAULT 0");
  await query("ALTER TABLE contracts ADD COLUMN IF NOT EXISTS discount_amount NUMERIC(14,2) NOT NULL DEFAULT 0");
  // Every existing contract becomes "list price, no discount" exactly once. The
  // `discount_pct IS NULL` guard is a no-op on re-runs because the column is NOT NULL.
  await query(`
    UPDATE contracts
       SET original_price = value,
           discount_pct = 0,
           discount_amount = 0
     WHERE original_price IS NULL
  `);
  // The calculated discount is derived, so it is kept consistent with the inputs.
  await query(`
    UPDATE contracts
       SET discount_amount = ROUND(original_price * discount_pct / 100, 2)
     WHERE original_price IS NOT NULL
  `);
  // `value` is the final price by definition; recompute it so the invariant holds
  // for every row, existing and new.
  await query(`
    UPDATE contracts
       SET value = original_price - discount_amount
     WHERE original_price IS NOT NULL AND discount_amount IS NOT NULL
  `);
  await query("ALTER TABLE contracts ALTER COLUMN original_price SET NOT NULL");
  await query("ALTER TABLE contracts ALTER COLUMN original_price SET DEFAULT 0");
}

